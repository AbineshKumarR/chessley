/**
 * Get PST evaluation bonus for a piece at given coordinates.
 * @param {string} type - Piece type ('p', 'n', 'b', 'r', 'q', 'k')
 * @param {string} color - Piece color ('w' or 'b')
 * @param {number} row - Board row (0-7, where 0 is rank 8, 7 is rank 1)
 * @param {number} col - Board col (0-7, where 0 is file a, 7 is file h)
 * @param {boolean} isEndgame - Whether the position is in endgame phase
 * @returns {number} Score bonus in centipawns
 */
export function getPieceSquareScore(type, color, row, col, isEndgame = false) {
  const actualRow = color === 'w' ? row : 7 - row;
  const index = actualRow * 8 + col;

  switch (type.toLowerCase()) {
    case 'p':
      return PAWN_TABLE[index] || 0;
    case 'n':
      return KNIGHT_TABLE[index] || 0;
    case 'b':
      return BISHOP_TABLE[index] || 0;
    case 'r':
      return ROOK_TABLE[index] || 0;
    case 'q':
      return QUEEN_TABLE[index] || 0;
    case 'k':
      return isEndgame ? (KING_ENDGAME_TABLE[index] || 0) : (KING_MIDDLEGAME_TABLE[index] || 0);
    default:
      return 0;
  }
}
